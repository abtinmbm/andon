"""Export the int8 CNN and its test vectors as C headers for the Stage 2 firmware.

    uv run python -m andon.export_c --config configs/phase4_idcnn_int8.yaml --machine fan
        --seed 0 --out firmware/model
    uv run python -m andon.export_c --synthetic --out firmware/build/model   (CI)

``--config`` exports a real model: the float checkpoint, quantized exactly as
``andon.quantize`` scored it (same calibration patches), with test vectors from the first
normal dev-test clip of that machine type. Its headers hold weights trained on
CC BY-NC-SA data, so they are written locally and not committed. ``--synthetic`` builds a
seeded model with the same layer shapes from synthetic audio; it needs no data, so CI runs
it and checks the whole export path.

Two headers are written, then read back and checked against the Python reference:

- ``andon_model.h``: per-band normalisation, the input quantization, and for each conv
  layer its int8 weights ``[out][in][3][3]``, int32 biases, fixed-point multipliers and
  shifts, stride, whether a 2x2 max pool comes first, and the output zero point; then the
  head (int8 weights ``[class][channel]``, int32 biases, float logit scales).
- ``andon_test_vectors.h``: int16 audio; its log-mel frames (H4 checks its C front end
  against them); ``ANDON_TV_N`` patches cut from those frames; and for each patch the int8
  input, every conv layer's int8 output, the head's int32 sums, the logits and the
  anomaly score ``-log p(true ID)`` (H5 checks its kernels against them).

Layouts: a log-mel patch is ``[frame][mel]``, as Python stores it. The int8 tensors are
``[channel][mel][frame]`` (channel-major, mels on the height axis), as the CNN sees them.

The arithmetic the C code must reproduce, bit for bit up to the head's sums:

- normalise in float32: ``x = (logmel - band_mean) / band_std``
- quantize in double: ``q = clamp(rint(x / input_scale) + input_zero, -128, 127)``
  (``rint``: round half to even; 128 values per frame, so software double is cheap)
- conv: ``acc = bias + sum(w * (q_in - zero_in))`` with 0 for padding, in int32
- rescale: ``q = clamp(((int64)acc * mult + (1 << (shift - 1))) >> shift) + zero_out``
- global pool: ``sum`` of ``q - zero`` over all positions; head: ``acc = bias + w . sum``
- logits in float: ``acc * head_scale``; score = ``-log softmax(logits)[true ID]``
"""

from __future__ import annotations

import argparse
import math
import re
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import torch
from torch import nn

from andon import quant, quantize, train_idcnn
from andon.data.audio import read_wav
from andon.data.dataset import dev_test_clips
from andon.experiment import Config, load_config
from andon.features.logmel import LogMelConfig, logmel
from andon.models.idcnn import IdCNN

CONFIGS = Path(__file__).resolve().parents[1] / "configs"
MODEL_HEADER = "andon_model.h"
VECTORS_HEADER = "andon_test_vectors.h"
N_VECTORS = 3  # patches in the test vectors
_PER_LINE = 16


@dataclass
class Export:
    """Everything that goes into the two headers."""

    qmodel: quant.QuantIdCNN
    classes: list[str]
    source: str  # where the model came from, for the header comment
    audio: np.ndarray  # int16
    logmel_cfg: LogMelConfig
    width: int  # frames per patch
    hop: int  # frames between patches
    true_id: int


# --- writing ----------------------------------------------------------------------------


def _c_float(v: float, double: bool = False) -> str:
    if not math.isfinite(v):
        raise ValueError(f"cannot export {v}")
    text = repr(float(v)) if double else f"{float(np.float32(v)):.9g}"  # both round-trip
    if not any(c in text for c in ".e"):
        text += ".0"
    return text if double else text + "f"


def c_array(ctype: str, name: str, values: np.ndarray, dims: str = "") -> str:
    """``static const`` C array of ``values`` (flattened); ``dims`` documents the layout."""
    flat = np.asarray(values).ravel()
    if ctype == "float":
        items = [_c_float(v) for v in flat]
    elif ctype == "double":
        items = [_c_float(v, double=True) for v in flat]
    else:
        items = [str(int(v)) for v in flat]
    lines = [", ".join(items[i : i + _PER_LINE]) for i in range(0, len(items), _PER_LINE)]
    comment = f"  /* {dims} */" if dims else ""
    body = ",\n    ".join(lines)
    return f"static const {ctype} {name}[{len(flat)}] = {{{comment}\n    {body}\n}};\n"


def _define(name: str, value: int | str) -> str:
    return f"#define {name} {value}\n"


def _guard(name: str, doc: str, body: list[str]) -> str:
    return (
        f"/* {doc} Generated by andon.export_c; do not edit. */\n"
        f"#ifndef {name}\n#define {name}\n\n#include <stdint.h>\n\n"
        + "\n".join(body)
        + f"\n#endif /* {name} */\n"
    )


def model_header(ex: Export) -> str:
    q = ex.qmodel
    n_mels = q.band_mean.size
    body = [
        _define("ANDON_N_MELS", n_mels)
        + _define("ANDON_PATCH_FRAMES", ex.width)
        + _define("ANDON_SCORE_HOP", ex.hop)
        + _define("ANDON_N_CLASSES", len(ex.classes))
        + _define("ANDON_N_CONV", len(q.convs))
        + _define("ANDON_POOL_SIZE", q.pool_size),
        "/* Class index -> machine ID: "
        + ", ".join(f"{k} {c}" for k, c in enumerate(ex.classes))
        + " */\n",
        c_array("float", "andon_band_mean", q.band_mean),
        c_array("float", "andon_band_std", q.band_std),
        f"static const double andon_input_scale = {_c_float(q.input_q.scale, double=True)};\n"
        f"static const int32_t andon_input_zero = {q.input_q.zero_point};\n",
    ]
    n_in = 1
    for i, layer in enumerate(q.convs):
        n_out = layer.weight.shape[0]
        p = f"ANDON_CONV{i}"
        body.append(
            _define(f"{p}_IN", n_in)
            + _define(f"{p}_OUT", n_out)
            + _define(f"{p}_STRIDE", layer.stride)
            + _define(f"{p}_POOL_BEFORE", int(layer.pool_before))
            + _define(f"{p}_OUT_ZERO", layer.out.zero_point)
            + c_array("int8_t", f"andon_conv{i}_weight", layer.weight, "[out][in][3][3]")
            + c_array("int32_t", f"andon_conv{i}_bias", layer.bias)
            + c_array("int32_t", f"andon_conv{i}_mult", layer.mult)
            + c_array("int8_t", f"andon_conv{i}_shift", layer.shift)
            + c_array("double", f"andon_conv{i}_out_scale", np.array([layer.out.scale]))
        )
        n_in = n_out
    body.append(
        c_array("int8_t", "andon_head_weight", q.head_weight, "[class][channel]")
        + c_array("int32_t", "andon_head_bias", q.head_bias)
        + c_array("float", "andon_head_scale", q.head_scale)
    )
    return _guard("ANDON_MODEL_H", f"Int8 machine-ID CNN: {ex.source}.", body)


@dataclass
class Vectors:
    logmel: np.ndarray  # (frames, mels) float32
    patches: np.ndarray  # (n, width, mels) float32
    inputs: np.ndarray  # (n, 1, mels, width) int8
    layers: list[np.ndarray]  # per conv layer, (n, c, h, w) int8
    head_acc: np.ndarray  # (n, classes) int64
    logits: np.ndarray  # (n, classes) float64
    scores: np.ndarray  # (n,) float64


def reference_vectors(ex: Export, n: int) -> Vectors:
    """Run the audio through the Python front end and the int8 reference."""
    frames = logmel(ex.audio.astype(np.float32) / 32768, ex.logmel_cfg)
    starts = np.arange(n) * ex.hop
    if starts[-1] + ex.width > len(frames):
        raise ValueError(f"{len(frames)} frames hold fewer than {n} patches")
    patches = frames[starts[:, None] + np.arange(ex.width)]
    inputs = ex.qmodel.quantize_input(patches)
    trace: list[np.ndarray] = []
    acc = ex.qmodel.head_acc(inputs, trace)
    logits = acc * ex.qmodel.head_scale
    scores = -quantize.log_softmax(logits)[:, ex.true_id]
    return Vectors(frames, patches, inputs, trace, acc, logits, scores)


def vectors_header(ex: Export, v: Vectors) -> str:
    n = len(v.patches)
    body = [
        _define("ANDON_TV_SAMPLE_RATE", ex.logmel_cfg.sample_rate)
        + _define("ANDON_TV_AUDIO_LEN", ex.audio.size)
        + _define("ANDON_TV_FRAMES", len(v.logmel))
        + _define("ANDON_TV_N", n)
        + _define("ANDON_TV_TRUE_ID", ex.true_id),
        "/* Audio as int16 PCM; the front end sees sample / 32768.0f. */\n"
        + c_array("int16_t", "andon_tv_audio", ex.audio),
        "/* Log-mel of the audio, centred frames, reflect-padded at both ends. */\n"
        + c_array("float", "andon_tv_logmel", v.logmel, "[frame][mel]"),
        f"/* Patch k is frames k * {ex.hop} to k * {ex.hop} + {ex.width - 1} of the log-mel. */\n"
        + c_array("float", "andon_tv_patch", v.patches, "[n][frame][mel]")
        + c_array("int8_t", "andon_tv_input", v.inputs, "[n][1][mel][frame]"),
    ]
    for i, t in enumerate(v.layers):
        dims = "][".join(str(k) for k in t.shape[1:])
        body.append(c_array("int8_t", f"andon_tv_conv{i}", t, f"[n][{dims}]"))
    body.append(
        c_array("int32_t", "andon_tv_head_acc", v.head_acc, "[n][class]")
        + c_array("float", "andon_tv_logits", v.logits, "[n][class]")
        + c_array("float", "andon_tv_score", v.scores, "[n]")
    )
    return _guard("ANDON_TEST_VECTORS_H", f"Test vectors for {ex.source}, {n} patches.", body)


# --- reading back -----------------------------------------------------------------------

_ARRAY = re.compile(r"static const (\w+) (\w+)\[(\d+)\] = \{(?:\s*/\*.*?\*/)?([^}]*)\};", re.S)
_SCALAR = re.compile(r"static const (\w+) (\w+) = ([^;]+);")
_DEFINE = re.compile(r"#define (ANDON_\w+) (-?\d+)")
_DTYPES = {
    "int8_t": np.int8,
    "int16_t": np.int16,
    "int32_t": np.int32,
    "float": np.float32,
    "double": np.float64,
}


def read_header(text: str) -> tuple[dict[str, np.ndarray], dict[str, int]]:
    """The arrays and scalars (as 1-element arrays) and the integer defines of a header."""
    arrays: dict[str, np.ndarray] = {}
    for ctype, name, size, body in _ARRAY.findall(text):
        items = [x.strip().rstrip("f") for x in body.split(",") if x.strip()]
        values = np.array([float(x) if ctype in ("float", "double") else int(x) for x in items])
        if len(values) != int(size):
            raise ValueError(f"{name}: {len(values)} values, declared {size}")
        arrays[name] = values.astype(_DTYPES[ctype])
    for ctype, name, value in _SCALAR.findall(text):
        arrays[name] = np.array([float(value.rstrip("f"))]).astype(_DTYPES[ctype])
    defines = {k: int(v) for k, v in _DEFINE.findall(text)}
    return arrays, defines


def model_from_header(text: str) -> quant.QuantIdCNN:
    a, d = read_header(text)
    convs = []
    for i in range(d["ANDON_N_CONV"]):
        n_in, n_out = d[f"ANDON_CONV{i}_IN"], d[f"ANDON_CONV{i}_OUT"]
        out_qp = quant.QParams(
            float(a[f"andon_conv{i}_out_scale"][0]), d[f"ANDON_CONV{i}_OUT_ZERO"]
        )
        convs.append(
            quant.QLayer(
                weight=a[f"andon_conv{i}_weight"].reshape(n_out, n_in, 3, 3),
                bias=a[f"andon_conv{i}_bias"],
                mult=a[f"andon_conv{i}_mult"].astype(np.int64),
                shift=a[f"andon_conv{i}_shift"].astype(np.int64),
                out=out_qp,
                stride=d[f"ANDON_CONV{i}_STRIDE"],
                pool_before=bool(d[f"ANDON_CONV{i}_POOL_BEFORE"]),
            )
        )
    n_classes = d["ANDON_N_CLASSES"]
    return quant.QuantIdCNN(
        band_mean=a["andon_band_mean"],
        band_std=a["andon_band_std"],
        input_q=quant.QParams(float(a["andon_input_scale"][0]), int(a["andon_input_zero"][0])),
        convs=convs,
        head_weight=a["andon_head_weight"].reshape(n_classes, -1),
        head_bias=a["andon_head_bias"],
        head_scale=a["andon_head_scale"].astype(np.float64),
        pool_size=d["ANDON_POOL_SIZE"],
    )


def verify(out_dir: Path, logmel_cfg: LogMelConfig) -> None:
    """Re-read both headers and check every vector against the Python reference.

    The model rebuilt from the header must reproduce the int8 tensors and int32 sums
    exactly; the floats in the header are float32, so the logits and scores get a tolerance.
    """
    model_text = (out_dir / MODEL_HEADER).read_text(encoding="utf-8")
    tv, d = read_header((out_dir / VECTORS_HEADER).read_text(encoding="utf-8"))
    qmodel = model_from_header(model_text)
    n = d["ANDON_TV_N"]
    _, md = read_header(model_text)
    width, hop, n_mels = md["ANDON_PATCH_FRAMES"], md["ANDON_SCORE_HOP"], md["ANDON_N_MELS"]

    frames = logmel(tv["andon_tv_audio"].astype(np.float32) / 32768, logmel_cfg)
    np.testing.assert_array_equal(frames.ravel(), tv["andon_tv_logmel"])
    patches = tv["andon_tv_patch"].reshape(n, width, n_mels)
    starts = np.arange(n) * hop
    np.testing.assert_array_equal(patches, frames[starts[:, None] + np.arange(width)])

    inputs = qmodel.quantize_input(patches)
    np.testing.assert_array_equal(inputs.ravel(), tv["andon_tv_input"])
    trace: list[np.ndarray] = []
    acc = qmodel.head_acc(inputs, trace)
    for i, t in enumerate(trace):
        np.testing.assert_array_equal(t.ravel(), tv[f"andon_tv_conv{i}"])
    np.testing.assert_array_equal(acc.ravel(), tv["andon_tv_head_acc"])
    logits = acc * qmodel.head_scale
    np.testing.assert_allclose(logits.ravel(), tv["andon_tv_logits"], rtol=1e-5, atol=1e-5)
    scores = -quantize.log_softmax(logits)[:, d["ANDON_TV_TRUE_ID"]]
    np.testing.assert_allclose(scores, tv["andon_tv_score"], rtol=1e-5, atol=1e-5)


def write(ex: Export, out_dir: Path, n: int = N_VECTORS) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = [out_dir / MODEL_HEADER, out_dir / VECTORS_HEADER]
    paths[0].write_text(model_header(ex), encoding="utf-8", newline="\n")
    paths[1].write_text(
        vectors_header(ex, reference_vectors(ex, n)), encoding="utf-8", newline="\n"
    )
    verify(out_dir, ex.logmel_cfg)
    return paths


# --- sources ----------------------------------------------------------------------------


def _audio_for(n: int, width: int, hop: int, cfg: LogMelConfig) -> int:
    """Samples whose centred log-mel has exactly the frames ``n`` patches need."""
    return (width + (n - 1) * hop - 1) * cfg.hop_length


def synthetic_export(seed: int = 0, n: int = N_VECTORS) -> Export:
    """A seeded CNN with the final model's layer shapes, fed by synthetic machine audio.

    Each of four "machines" is a hum at its own frequency with harmonics and noise; the
    weights are random but batch norm statistics and band normalisation are real, from
    the synthetic audio, so activations have realistic ranges.
    """
    src = load_config(CONFIGS / "phase3_idcnn_mixup.yaml")
    m = src.raw["model"]
    width, hop, cfg = int(m["patch_frames"]), int(m["score_hop"]), src.logmel
    rng = np.random.default_rng(seed)
    t = np.arange(cfg.sample_rate * 5) / cfg.sample_rate  # 156 frames, room for 4 patches

    def machine(k: int) -> np.ndarray:
        f0 = 120.0 * (k + 1)
        y = sum(0.2 / h * np.sin(2 * np.pi * f0 * h * t + rng.uniform(0, 6)) for h in (1, 2, 3))
        y = y + 0.02 * rng.standard_normal(t.size)
        return np.round(np.clip(y, -1, 1) * 32767).astype(np.int16)

    clips = [machine(k % 4) for k in range(16)]
    feats = [logmel(c.astype(np.float32) / 32768, cfg) for c in clips]
    torch.manual_seed(seed)
    model = IdCNN(4, cfg.n_mels, tuple(m["channels"]))
    model.set_normalization(torch.from_numpy(np.concatenate(feats)))
    with torch.no_grad():  # batch norm statistics from the synthetic patches
        model.train()
        x = torch.from_numpy(np.stack([f[:width] for f in feats]))
        for mod in model.modules():
            if isinstance(mod, nn.BatchNorm2d):
                mod.momentum = None  # cumulative average
        for _ in range(3):
            model(x)
    model.eval()
    calib = torch.from_numpy(np.stack([f[i : i + width] for f in feats for i in (0, 16, 30)]))
    qmodel = quant.quantize_idcnn(model, calib)
    audio = machine(1)[: _audio_for(n, width, hop, cfg)]
    classes = [f"id_{k:02d}" for k in range(4)]
    return Export(qmodel, classes, f"synthetic, seed {seed}", audio, cfg, width, hop, 1)


def real_export(cfg: Config, machine_type: str, seed: int, n: int = N_VECTORS) -> Export:
    """The int8 model ``andon.quantize`` scored for this type and seed, with vectors from
    the first normal dev-test clip of the type (in name order)."""
    if cfg.model != "id_cnn_int8":
        raise ValueError("only the int8 machine-ID CNN can be exported")
    src = quantize.source_config(cfg)
    m = src.raw["model"]
    width, hop = int(m["patch_frames"]), int(m["score_hop"])
    train_feats, _, classes = train_idcnn.training_data(src, machine_type)
    model, ckpt = train_idcnn.load_checkpoint(
        src.checkpoint_path(machine_type, seed), src, quantize.CPU
    )
    if ckpt["classes"] != classes:
        raise ValueError(f"checkpoint IDs {ckpt['classes']} differ from the data's {classes}")
    n_calib = min(int(cfg.raw["quantize"]["calib_clips"]), train_feats.n_clips)
    qmodel = quantize.calibrated_cnn(model, train_feats, width, n_calib, seed)

    clip = sorted(
        (c for c in dev_test_clips(src.data_root, machine_type) if not c.is_anomaly),
        key=lambda c: c.path.name,
    )[0]
    samples, _ = read_wav(clip.path)
    pcm = np.round(samples * 32768).astype(np.int16)
    if not np.array_equal(pcm.astype(np.float32) / 32768, samples.astype(np.float32)):
        raise ValueError(f"{clip.path} is not 16-bit PCM")
    audio = pcm[: _audio_for(n, width, hop, src.logmel)]
    source = f"{cfg.name}, {machine_type}, seed {seed}; vectors from {clip.path.name}"
    return Export(
        qmodel, classes, source, audio, src.logmel, width, hop, classes.index(clip.machine_id)
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Export the int8 CNN as C headers.")
    parser.add_argument("--synthetic", action="store_true", help="seeded model, no data needed")
    parser.add_argument("--config", type=Path, help="an id_cnn_int8 config")
    parser.add_argument("--machine", help="machine type, with --config")
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--vectors", type=int, default=N_VECTORS, help="test patches")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)

    if args.synthetic == bool(args.config):
        parser.error("give exactly one of --synthetic or --config")
    if args.config:
        if not args.machine:
            parser.error("--config needs --machine")
        ex = real_export(load_config(args.config), args.machine, args.seed, args.vectors)
    else:
        ex = synthetic_export(args.seed, args.vectors)
    for path in write(ex, args.out, args.vectors):
        print(f"wrote {path} ({path.stat().st_size / 1024:.0f} KB)")
    print(f"verified: {args.vectors} test vectors reproduce through the header model")
    print(f"model data: {ex.qmodel.nbytes() / 1024:.1f} KB int8 ({ex.source})")


if __name__ == "__main__":
    main()
